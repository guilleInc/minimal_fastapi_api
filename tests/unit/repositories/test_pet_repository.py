class TestDeletePet:
    """Tests for SqlaPetRepository.delete_pet()"""

    @pytest.mark.asyncio
    async def test_delete_pet_removes_existing_pet(self, repository: SqlaPetRepository) -> None:
        """Test successfully deleting an existing pet."""
        created_pet = await repository.add_pet(
            PetCreate(
                name="Milo",
                species="cat",
                breed="Siamese",
                color="cream",
                owner_name="Charlie",
                age=3,
            )
        )

        deleted = await repository.delete_pet(created_pet.id)
        pet = await repository.get_pet(created_pet.id)

        assert deleted is True
        assert pet is None

    @pytest.mark.asyncio
    async def test_delete_pet_returns_false_when_missing(
        self, repository: SqlaPetRepository
    ) -> None:
        """Test deleting a non-existent pet returns False."""
        deleted = await repository.delete_pet(999)

        assert deleted is False
