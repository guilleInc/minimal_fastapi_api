class TestUpdatePet:
    """Tests for SqlaPetRepository.update_pet()"""

    @pytest.mark.asyncio
    async def test_update_pet_updates_only_provided_fields(
        self, repository: SqlaPetRepository
    ) -> None:
        """Test updating only specific fields of an existing pet."""
        created_pet = await repository.add_pet(
            PetCreate(
                name="Milo",
                species="cat",
                breed="Siamese",
                color="cream",
                owner_name="Charlie",
                age=3,
            )
        )
        payload = PetUpdate(age=4)

        updated_pet = await repository.update_pet(created_pet.id, payload)

        assert updated_pet is not None
        assert updated_pet.id == created_pet.id
        assert updated_pet.name == "Milo"
        assert updated_pet.species == "cat"
        assert updated_pet.breed == "Siamese"
        assert updated_pet.color == "cream"
        assert updated_pet.owner_name == "Charlie"
        assert updated_pet.age == 4

