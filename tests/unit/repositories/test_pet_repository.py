import pytest

from app.domain.pets import PetCreate, PetUpdate
from app.repositories.pet_repository import SqlaPetRepository


class TestAddPet:
    """Tests for SqlaPetRepository.add_pet()"""

    @pytest.mark.asyncio
    async def test_add_pet_persists_and_returns_pet(self, repository: SqlaPetRepository) -> None:
        """Test successfully adding a pet and verifying persistence."""
        payload = PetCreate(
            name="Milo", species="cat", breed="Siamese", color="cream", owner_name="Charlie", age=3
        )

        pet = await repository.add_pet(payload)

        assert pet.id is not None
        assert pet.name == "Milo"
        assert pet.species == "cat"
        assert pet.breed == "Siamese"
        assert pet.color == "cream"
        assert pet.owner_name == "Charlie"
        assert pet.age == 3

    @pytest.mark.asyncio
    async def test_add_pet_returns_pet_with_generated_id(
        self, repository: SqlaPetRepository
    ) -> None:
        """Test that added pet has an ID generated by the database."""
        payload = PetCreate(
            name="Whiskers",
            species="dog",
            breed="Golden Retriever",
            color="golden",
            owner_name="David",
            age=2,
        )

        pet = await repository.add_pet(payload)

        assert pet.id > 0


class TestGetPets:
    """Tests for SqlaPetRepository.get_pets()"""

    @pytest.mark.asyncio
    async def test_get_pets_returns_all_pets(self, repository: SqlaPetRepository) -> None:
        """Test retrieving all pets from the repository."""
        await repository.add_pet(
            PetCreate(
                name="Milo",
                species="cat",
                breed="Siamese",
                color="cream",
                owner_name="Charlie",
                age=3,
            )
        )
        await repository.add_pet(
            PetCreate(
                name="Bolt",
                species="dog",
                breed="Golden Retriever",
                color="golden",
                owner_name="David",
                age=5,
            )
        )

        pets = await repository.get_pets()

        assert len(pets) == 2
        assert {pet.name for pet in pets} == {"Milo", "Bolt"}

    @pytest.mark.asyncio
    async def test_get_pets_returns_empty_list_when_no_pets(
        self, repository: SqlaPetRepository
    ) -> None:
        """Test retrieving pets when none exist."""
        pets = await repository.get_pets()

        assert pets == []
        assert len(pets) == 0


