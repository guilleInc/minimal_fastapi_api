class TestDeletePet:
    """Tests for SqlaPetRepository.delete_pet()"""

    @pytest.mark.asyncio
    async def test_delete_pet_removes_existing_pet(self, pet_repository: SqlaPetRepository) -> None:
        """Test successfully deleting an existing pet."""
        # Arrange
        payload = PetCreate(
            name="Milo",
            species="cat",
            breed="Siamese",
            color="cream",
            owner_name="Charlie",
            age=3,
        )

        # Act
        created_pet = await pet_repository.add_pet(payload)
        deleted = await pet_repository.delete_pet(created_pet.id)
        pet = await pet_repository.get_pet(created_pet.id)

        # Assert
        assert deleted is True
        assert pet is None

    @pytest.mark.asyncio
    async def test_delete_pet_returns_false_when_missing(
        self, pet_repository: SqlaPetRepository
    ) -> None:
        """Test deleting a non-existent pet returns False."""
        # Act
        deleted = await pet_repository.delete_pet(999)

        # Assert
        assert deleted is False
