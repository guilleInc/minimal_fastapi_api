import pytest

from app.domain.pets import PetCreate, PetUpdate
from app.repositories.pet_repository import SqlaPetRepository


class TestAddPet:
    """Tests for SqlaPetRepository.add_pet()"""

    @pytest.mark.asyncio
    async def test_add_pet_persists_and_returns_pet(
        self, pet_repository: SqlaPetRepository
    ) -> None:
        """Test successfully adding a pet and verifying persistence."""
        # Arrange
        payload = PetCreate(
            name="Milo", species="cat", breed="Siamese", color="cream", owner_name="Charlie", age=3
        )

        # Act
        pet = await pet_repository.add_pet(payload)

        # Assert
        assert pet.id is not None
        assert pet.name == "Milo"
        assert pet.species == "cat"
        assert pet.breed == "Siamese"
        assert pet.color == "cream"
        assert pet.owner_name == "Charlie"
        assert pet.age == 3

    @pytest.mark.asyncio
    async def test_add_pet_returns_pet_with_generated_id(
        self, pet_repository: SqlaPetRepository
    ) -> None:
        """Test that added pet has an ID generated by the database."""
        # Arrange
        payload = PetCreate(
            name="Whiskers",
            species="dog",
            breed="Golden Retriever",
            color="golden",
            owner_name="David",
            age=2,
        )

        # Act
        pet = await pet_repository.add_pet(payload)

        # Assert
        assert pet.id > 0


class TestGetPets:
    """Tests for SqlaPetRepository.get_pets()"""

    @pytest.mark.asyncio
    async def test_get_pets_returns_all_pets(self, pet_repository: SqlaPetRepository) -> None:
        """Test retrieving all pets from the repository."""
        # Arrange
        first_payload = PetCreate(
            name="Milo",
            species="cat",
            breed="Siamese",
            color="cream",
            owner_name="Charlie",
            age=3,
        )
        second_payload = PetCreate(
            name="Bolt",
            species="dog",
            breed="Golden Retriever",
            color="golden",
            owner_name="David",
            age=5,
        )

        # Act
        await pet_repository.add_pet(first_payload)
        await pet_repository.add_pet(second_payload)
        pets = await pet_repository.get_pets()

        # Assert
        assert len(pets) == 2
        assert {pet.name for pet in pets} == {"Milo", "Bolt"}

    @pytest.mark.asyncio
    async def test_get_pets_returns_empty_list_when_no_pets(
        self, pet_repository: SqlaPetRepository
    ) -> None:
        """Test retrieving pets when none exist."""
        # Act
        pets = await pet_repository.get_pets()

        # Assert
        assert pets == []
        assert len(pets) == 0


