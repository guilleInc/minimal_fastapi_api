import pytest
from sqlalchemy.ext.asyncio import AsyncSession

from app.domain.users import UserCreate, UserUpdate
from app.repositories.user_repository import SqlaUserRepository, UserIntegrityError


class TestAddUser:
    """Tests for SqlaUserRepository.add_user()."""

    @pytest.mark.asyncio
    async def test_add_user_persists_and_returns_user(
        self, user_repository: SqlaUserRepository
    ) -> None:
        """Test successfully adding a user and verifying its returned fields."""
        # Arrange
        payload = UserCreate(
            username="alice",
            email="alice@example.com",
            full_name="Alice Smith",
            disabled=False,
            hashed_password="hashed-password",
        )

        # Act
        user = await user_repository.add_user(payload)

        # Assert
        assert user.id is not None
        assert user.username == "alice"
        assert user.email == "alice@example.com"
        assert user.full_name == "Alice Smith"
        assert user.disabled is False

    @pytest.mark.asyncio
    async def test_add_user_returns_user_with_generated_id(
        self, user_repository: SqlaUserRepository
    ) -> None:
        """Test that an added user has an ID generated by the database."""
        # Arrange
        payload = UserCreate(
            username="bob",
            email="bob@example.com",
            full_name="Bob Jones",
            disabled=False,
            hashed_password="hashed-password",
        )

        # Act
        user = await user_repository.add_user(payload)

        # Assert
        assert user.id > 0

    @pytest.mark.asyncio
    async def test_add_user_raises_integrity_error_for_duplicate_username(
        self, user_repository: SqlaUserRepository, session: AsyncSession
    ) -> None:
        """Test that duplicate usernames are reported as repository integrity errors."""
        # Arrange
        existing_payload = UserCreate(
            username="alice",
            email="alice@example.com",
            full_name="Alice Smith",
            disabled=False,
            hashed_password="hashed-password",
        )
        duplicate_payload = UserCreate(
            username="alice",
            email="another@example.com",
            full_name="Another User",
            disabled=False,
            hashed_password="another-password",
        )

        # Act and Assert
        await user_repository.add_user(existing_payload)
        with pytest.raises(UserIntegrityError):
            await user_repository.add_user(duplicate_payload)


