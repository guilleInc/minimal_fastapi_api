class TestUpdateUser:
    """Tests for SqlaUserRepository.update_user()."""

    @pytest.mark.asyncio
    async def test_update_user_updates_only_provided_fields(
        self, user_repository: SqlaUserRepository
    ) -> None:
        """Test updating only specific fields of an existing user."""
        # Arrange
        create_payload = UserCreate(
            username="alice",
            email="alice@example.com",
            full_name="Alice Smith",
            disabled=False,
            hashed_password="hashed-password",
        )
        update_payload = UserUpdate(full_name="Alice Jones")

        # Act
        created_user = await user_repository.add_user(create_payload)
        updated_user = await user_repository.update_user(created_user.id, update_payload)

