class TestDeleteUser:
    """Tests for SqlaUserRepository.delete_user()."""

    @pytest.mark.asyncio
    async def test_delete_user_removes_existing_user(
        self, user_repository: SqlaUserRepository
    ) -> None:
        """Test successfully deleting an existing user."""
        # Arrange
        payload = UserCreate(
            username="alice",
            email="alice@example.com",
            full_name="Alice Smith",
            disabled=False,
            hashed_password="hashed-password",
        )

        # Act
        created_user = await user_repository.add_user(payload)
        deleted = await user_repository.delete_user(created_user.id)
        user = await user_repository.get_user(created_user.id)

        # Assert
        assert deleted is True
        assert user is None

    @pytest.mark.asyncio
    async def test_delete_user_returns_false_when_missing(
        self, user_repository: SqlaUserRepository
    ) -> None:
        """Test deleting a non-existent user returns False."""
        # Act
        deleted = await user_repository.delete_user(999)

        # Assert
        assert deleted is False
